"""Prepare immutable monthly gzip chunks locally. Never uploads or publishes data.

Input: the combined-manifest.json generated by the personal archive downloader.
Example: python tools/package-market-history.py --root LOCAL_ARCHIVES --out LOCAL_PACKAGES
"""
import argparse,csv,gzip,hashlib,json,re
from pathlib import Path
from datetime import datetime,timezone
from decimal import Decimal

def package_file(path,provider,symbol,frame,out):
    if not re.fullmatch(r'[a-z0-9_-]+',provider) or not re.fullmatch(r'[A-Z0-9]{3,20}',symbol) or frame not in ('M1','H1','D1'):
        raise ValueError('Invalid archive identity')
    groups={};previous=-1
    with path.open(newline='',encoding='utf8') as stream:
        for row in csv.DictReader(stream):
            dt=datetime.fromisoformat(row['Date'].replace('Z','+00:00'))
            if dt.utcoffset()!=timezone.utc.utcoffset(dt):raise ValueError('Input must use UTC timestamps')
            stamp=int(dt.timestamp());values=[row[k].strip() for k in ('Open','High','Low','Close')]
            o,h,l,c=map(Decimal,values)
            if not all(v.is_finite() for v in (o,h,l,c)) or not (0<l<=min(o,c)<=max(o,c)<=h) or stamp<=previous:
                raise ValueError('Invalid, duplicate or unordered candle')
            previous=stamp;groups.setdefault(dt.strftime('%Y-%m'),[]).append([stamp,*values])
    result=[]
    for month,rows in sorted(groups.items()):
        body={'schema':1,'provider':provider,'symbol':symbol,'timeframe':frame,'timezone':'UTC','price_side':'bid','columns':['time','open','high','low','close'],'candles':rows}
        raw=json.dumps(body,separators=(',',':'),ensure_ascii=True).encode();compressed=gzip.compress(raw,mtime=0)
        digest=hashlib.sha256(compressed).hexdigest();key=f'{provider}/{symbol}/{frame}/{month}/{digest}.json.gz'
        target=out/key;target.parent.mkdir(parents=True,exist_ok=True)
        if not target.exists():
            tmp=target.with_suffix('.part');tmp.write_bytes(compressed);tmp.replace(target)
        result.append({'provider':provider,'symbol':symbol,'timeframe':frame,'month':month+'-01','sha256':digest,'object_path':key,'candle_count':len(rows),'first_utc':datetime.fromtimestamp(rows[0][0],timezone.utc).isoformat(),'last_utc':datetime.fromtimestamp(rows[-1][0],timezone.utc).isoformat(),'bytes':len(compressed),'published':False})
    return result

def main():
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--root',type=Path,required=True);parser.add_argument('--out',type=Path,required=True)
    args=parser.parse_args();root=args.root.resolve();out=args.out.resolve();manifest=json.loads((root/'combined-manifest.json').read_text());chunks=[]
    for dataset in manifest['datasets']:
        source=(root/dataset['path']).resolve()
        if not source.is_relative_to(root):raise ValueError('Source outside archive directory')
        chunks.extend(package_file(source,'histdata',dataset['pair'],dataset['frame'],out))
    total=sum(c['bytes'] for c in chunks)
    report={'schema':1,'generated_at':datetime.now(timezone.utc).isoformat(),'source_snapshot_at':manifest['generated_at'],'not_uploaded':True,'source_download_complete':all(d['download_complete'] for d in manifest['datasets']),'datasets':chunks,'total_bytes':total,'within_1GB_storage':total<=1000000000,'largest_file_bytes':max((c['bytes'] for c in chunks),default=0)}
    out.mkdir(parents=True,exist_ok=True);(out/'upload-manifest.json').write_text(json.dumps(report,indent=2),encoding='utf8')
    print(json.dumps({k:v for k,v in report.items() if k!='datasets'}))

if __name__=='__main__':main()
